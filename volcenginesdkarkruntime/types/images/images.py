from typing import List, Optional

from volcenginesdkarkruntime._models import BaseModel

__all__ = [
    "OptimizePromptOptions",
    "SequentialImageGenerationOptions",
    "BoundingBox",
    "ImagesResponse",
    "ContentGenerationTool"
]


class OptimizePromptOptions(BaseModel):
    thinking: Optional[str] = None
    mode: Optional[str] = None


class SequentialImageGenerationOptions(BaseModel):
    max_images: Optional[int] = None
    """ Maximum number of images to generate in this request; effective only when the multi-image feature is enabled """


class ToolUsage(BaseModel):
    web_search: Optional[int] = None
    """The number of web search."""


class Usage(BaseModel):
    input_images: Optional[int] = None
    """The number of reference images supplied by the client."""
    generated_images: int
    """The number of images generated."""
    output_tokens: Optional[int] = None
    """The number of images generated by this request."""
    total_tokens: Optional[int] = None
    """The total number of images generated by this request."""
    tool_usage: Optional[ToolUsage] = None
    """The total number of images generated by this request."""


class BoundingBox(BaseModel):
    absolute: Optional[List[int]] = None
    """Coordinates in base-image pixels, with the origin at the top left."""

    normalized: Optional[List[int]] = None
    """Coordinates scaled to the integer range from 0 to 1000."""


class Image(BaseModel):
    url: str
    """The URL of the generated image, if any."""

    b64_json: str
    """The Base 64 encoded string of the generated image, if any."""

    size: str
    """The size of the generated image, if any."""

    output_format: Optional[str] = None
    """The actual container or codec used for this image."""

    z_index: Optional[int] = None
    """The layer stacking order; the base image is zero."""

    bounding_box: Optional[BoundingBox] = None
    """The layer region in the base image; omitted for the base image."""

    name: Optional[str] = None
    """The model-generated layer label; omitted for the base image."""

    description: Optional[str] = None
    """The model-generated semantic description; omitted for the base image."""


class Error(BaseModel):
    message: str
    """The reason for failed image generation"""

    code: str
    """The error code for failed image generation"""


class ContentGenerationTool(BaseModel):
    type: str
    """The content generation tool used to generate the images."""


class ImagesResponse(BaseModel):
    model: str
    """The model used to generated the images."""

    data: List[Image]
    """The generated images."""

    error: Error
    """The error body, if applicable."""

    usage: Usage
    """The usage information for the generation of images."""

    created_at: int
    """The Unix timestamp when the image was generated."""

    tool: List[ContentGenerationTool]
    """ The tool used to generate the image."""
